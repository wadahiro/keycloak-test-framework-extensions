package io.github.wadahiro.keycloak.testframework.undertow;

import java.lang.reflect.*;
import java.net.URLClassLoader;
import java.nio.file.*;
import java.sql.*;
import java.util.*;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.io.TempDir;
import static org.junit.jupiter.api.Assertions.*;

/** Exercise the JDBC implementation packaged in the selected runtime without leaking its classes into the runner. */
class H2SnapshotStorageIT {
    @TempDir static Path directory;
    static URLClassLoader loader;
    static Constructor<?> capture;
    static Method restore, close;
    static Driver driver;
    @BeforeAll static void loadSelectedStorage() throws Exception {
        RuntimeDescriptor runtime = RuntimeDescriptor.select(System.getProperty("kc.test.undertow.version"));
        java.net.URL[] runtimeJars = Arrays.stream(runtime.classpath().split(java.util.regex.Pattern.quote(java.io.File.pathSeparator)))
                .map(Path::of).map(path -> {
                    try { return path.toUri().toURL(); }
                    catch (java.net.MalformedURLException failure) { throw new IllegalArgumentException(failure); }
                }).toArray(java.net.URL[]::new);
        loader=new URLClassLoader(runtimeJars,ClassLoader.getPlatformClassLoader());
        String prefix=runtime.version().startsWith("15.") ? "runtime15" : "runtimemodern";
        Class<?> type=loader.loadClass("io.github.wadahiro.keycloak.testframework."+prefix+".H2DatabaseSnapshot");
        capture=type.getDeclaredConstructor(Connection.class);capture.setAccessible(true);
        restore=type.getDeclaredMethod("restore");restore.setAccessible(true);
        close=type.getDeclaredMethod("close");close.setAccessible(true);
        driver=(Driver)loader.loadClass("org.h2.Driver").getConstructor().newInstance();
    }
    @AfterAll static void releaseLoader() throws Exception {
        if(loader!=null) {
            try { loader.loadClass("org.h2.Driver").getMethod("unload").invoke(null); }
            catch(NoSuchMethodException ignored) { }
            loader.close();
        }
    }
    Connection connect() throws SQLException {
        Properties properties=new Properties();properties.setProperty("user","sa");properties.setProperty("password","");
        return driver.connect("jdbc:h2:mem:"+UUID.randomUUID(),properties);
    }
    static Object snapshot(Connection db) throws Exception { return invokeConstructor(capture,db); }
    static Object invokeConstructor(Constructor<?> c, Object value) throws Exception {
        try { return c.newInstance(value); } catch(InvocationTargetException e) { throw (Exception)e.getCause(); }
    }
    static void invoke(Method m, Object target) throws Exception {
        try { m.invoke(target); } catch(InvocationTargetException e) { throw (Exception)e.getCause(); }
    }
    @Test void restoresLargeLobsIdentitySequencesAndForeignKeysRepeatedly() throws Exception {
        try(Connection db=connect();Statement st=db.createStatement()) {
            st.execute("CREATE SEQUENCE ticket START WITH 7 INCREMENT BY 3");
            st.execute("CREATE TABLE parent(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, text_value CLOB, binary_value BLOB, optional_value VARCHAR)");
            st.execute("CREATE TABLE child(id INT PRIMARY KEY, parent_id BIGINT REFERENCES parent(id))");
            String text="baseline ".repeat(2000);byte[] binary=new byte[20000];Arrays.fill(binary,(byte)71);
            try(var insert=db.prepareStatement("INSERT INTO parent(text_value,binary_value) VALUES(?,?)")) {
                insert.setString(1,text);insert.setBytes(2,binary);insert.executeUpdate();
            }
            st.execute("INSERT INTO child VALUES(1,1)");
            Object state=snapshot(db);
            try {
                for(int i=0;i<3;i++) {
                    st.execute("DELETE FROM child");st.execute("DELETE FROM parent");
                    st.execute("INSERT INTO parent(text_value) VALUES('changed')");
                    st.executeQuery("SELECT NEXT VALUE FOR ticket").close();
                    invoke(restore,state);
                    try(var rs=st.executeQuery("SELECT * FROM parent")) {
                        assertTrue(rs.next());assertEquals(1,rs.getLong("id"));assertEquals(text,rs.getString("text_value"));
                        assertArrayEquals(binary,rs.getBytes("binary_value"));assertNull(rs.getString("optional_value"));assertFalse(rs.next());
                    }
                    try(var rs=st.executeQuery("SELECT NEXT VALUE FOR ticket")) { rs.next();assertEquals(7,rs.getLong(1)); }
                    try(var rs=st.executeQuery("SELECT parent_id FROM child")) { assertTrue(rs.next());assertEquals(1,rs.getLong(1)); }
                    st.execute("INSERT INTO parent(text_value) VALUES('next')");
                    try(var rs=st.executeQuery("SELECT MAX(id) FROM parent")) { rs.next();assertEquals(2,rs.getLong(1)); }
                    assertThrows(SQLException.class,()->st.execute("INSERT INTO child VALUES(2,999)"));
                }
            } finally { invoke(close,state); }
        }
    }
    @Test void schemaChangesFailBeforeTruncationAndPreventSnapshotReuse() throws Exception {
        try(Connection db=connect();Statement st=db.createStatement()) {
            st.execute("CREATE TABLE example(id INT PRIMARY KEY)");st.execute("INSERT INTO example VALUES(1)");
            Object state=snapshot(db);
            try {
                st.execute("ALTER TABLE example ADD COLUMN extra INT");
                assertThrows(SQLException.class,()->invoke(restore,state));
                try(var rs=st.executeQuery("SELECT COUNT(*) FROM example")) { rs.next();assertEquals(1,rs.getInt(1)); }
                assertThrows(IllegalStateException.class,()->invoke(restore,state));
            } finally { invoke(close,state); }
        }
    }
}
